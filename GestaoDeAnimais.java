package TrabalhoFinalPOO;

public class GestaoDeAnimais {
    private String nome, especie, raca, porte, estadoDeSaude, dataDeResgate, statusDaAdocao;
    private int idade;

    public GestaoDeAnimais(String nome, String especie, String raca, String porte, String estadoDeSaude, String dataDeResgate, String statusDaAdocao, int idade){
        this.nome = nome;
        this.especie = especie;
        this.raca = raca;
        this.porte = porte;
        this.estadoDeSaude = estadoDeSaude;
        this.dataDeResgate = dataDeResgate;
        this.statusDaAdocao = statusDaAdocao;
        this.idade = idade;
    }

    
}